import { chromium } from "@playwright/test";
const base = "http://127.0.0.1:4316";
const exe = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const browser = await chromium.launch({ executablePath: exe });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "zh-CN" });
const page = await ctx.newPage();
await page.goto(base + "/cases/run_d34a959a-e748-4208-b9a6-eac33c1de13a", { waitUntil: "networkidle" });
await page.waitForTimeout(1200);
console.log("CASE:", (await page.locator(".case-now").innerText()).replace(/\n+/g, " | ").slice(0, 320));
console.log("MAP:", (await page.locator(".evidence-map").first().innerText()).replace(/\n+/g, " | "));
console.log("DIFF:", (await page.locator(".correction-diff").first().innerText()).replace(/\n+/g, " | ").slice(0, 240));
await page.goto(base + "/archive/run_d34a959a-e748-4208-b9a6-eac33c1de13a", { waitUntil: "networkidle" });
await page.waitForTimeout(1200);
console.log("\nARCHIVE sections:", await page.locator(".trace-block h2, .trace-verdict-head h2, .trace-versionbar-head strong").allInnerTexts());
console.log("VERSION TABLE:", (await page.locator(".version-compare").innerText()).replace(/\n/g, " | ").slice(0, 500));
await ctx.close();
await browser.close();
